import 'package:flutter/material.dart';
import 'package:url_launcher/url_launcher.dart';
import '../../core/services/api_service.dart';

class ChatMessage {
  final String role; // 'user' or 'model'
  final String text;
  final DateTime timestamp;
  ChatMessage({required this.role, required this.text, DateTime? timestamp})
      : timestamp = timestamp ?? DateTime.now();
}

/// Reusable chatbot screen. Pass `pageContext` to tell the backend which
/// mode to behave in:
/// - Society assistant: {'page': 'marketplace'} / {'page': 'listings'} /
///   {'page': 'complaints'} / {'page': 'announcements'}
/// - Shop assistant: {'page': 'vendor-store', 'vendorId': vendor['_id'],
///   'vendorPhone': vendor['contactNumber']} or
///   {'page': 'product-detail', 'vendorId': vendorId, 'vendorPhone': ...}
///   `vendorPhone` is optional — when present, a WhatsApp button is shown
///   (matches the web widget's shop-assistant view).
class ChatbotScreen extends StatefulWidget {
  final Map<String, dynamic> pageContext;
  final String title;
  final String subtitle;

  const ChatbotScreen({
    super.key,
    required this.pageContext,
    this.title = "Resident Connect Assistant",
    this.subtitle = "Ask me anything",
  });

  @override
  State<ChatbotScreen> createState() => _ChatbotScreenState();
}

class _ChatbotScreenState extends State<ChatbotScreen> {
  static const Color _mint = Color(0xFF00C897);
  static const Color _mintBg = Color(0xFFE6F9F4);
  static const Color _navy = Color(0xFF1A2B47);
  static const Color _bg = Color(0xFFF8FAFB);
  static const Color _border = Color(0xFFE9EEF2);
  static const Color _whatsapp = Color(0xFF25D366);

  final TextEditingController _inputController = TextEditingController();
  final ScrollController _scrollController = ScrollController();
  final List<ChatMessage> _messages = [];
  bool _isSending = false;

  bool get _isShopContext =>
      widget.pageContext['page'] == 'vendor-store' ||
          widget.pageContext['page'] == 'product-detail';

  String? get _vendorPhone {
    final phone =
        widget.pageContext['vendorPhone'] ?? widget.pageContext['whatsappNumber'];
    if (phone == null) return null;
    final s = phone.toString().trim();
    return s.isEmpty ? null : s;
  }

  List<_QuickAction> get _quickActions => _isShopContext
      ? const [
    _QuickAction("What do you sell?", Icons.inventory_2_outlined),
    _QuickAction("Business hours", Icons.access_time_outlined),
    _QuickAction("Price range", Icons.sell_outlined),
    _QuickAction("Place an order", Icons.shopping_cart_outlined),
  ]
      : const [
    _QuickAction("SOPs & Rules", Icons.description_outlined),
    _QuickAction("Complaints", Icons.report_problem_outlined),
    _QuickAction("Marketplace", Icons.storefront_outlined),
    _QuickAction("Track My Order", Icons.local_shipping_outlined),
    _QuickAction("Announcements", Icons.campaign_outlined),
  ];

  @override
  void initState() {
    super.initState();
    // Greet the user immediately without waiting on the backend, matching
    // the greeting-shortcut logic the backend applies for an empty history.
    _messages.add(ChatMessage(
      role: 'model',
      text: _isShopContext
          ? "Hello! 👋 I'm this shop's assistant. Ask me about products, availability, pricing, or place an order."
          : "Hello! 👋 I'm the Resident Connect AI Assistant. Ask me anything about society rules, complaints, visitor parking, maintenance, or announcements.",
    ));
  }

  @override
  void dispose() {
    _inputController.dispose();
    _scrollController.dispose();
    super.dispose();
  }

  void _scrollToBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_scrollController.hasClients) {
        _scrollController.animateTo(
          _scrollController.position.maxScrollExtent,
          duration: const Duration(milliseconds: 250),
          curve: Curves.easeOut,
        );
      }
    });
  }

  Future<void> _sendMessage([String? quickText]) async {
    final text = (quickText ?? _inputController.text).trim();
    if (text.isEmpty || _isSending) return;

    // Build history from everything before this message (the backend maps
    // 'model' -> assistant and 'user' -> user; skip our local greeting since
    // it was never actually generated by the backend).
    final history = _messages
        .skip(1) // drop the local greeting bubble
        .map((m) => {'role': m.role, 'text': m.text})
        .toList();

    setState(() {
      _messages.add(ChatMessage(role: 'user', text: text));
      _isSending = true;
      _inputController.clear();
    });
    _scrollToBottom();

    final result = await ApiService.askChatbot(
      question: text,
      context: widget.pageContext,
      history: history,
    );

    if (!mounted) return;
    setState(() {
      _isSending = false;
      if (result['success'] == true) {
        _messages.add(ChatMessage(role: 'model', text: result['answer'] ?? ''));
      } else {
        _messages.add(ChatMessage(
          role: 'model',
          text: result['message'] ?? "Sorry, something went wrong. Please try again.",
        ));
      }
    });
    _scrollToBottom();
  }

  Future<void> _openWhatsApp() async {
    final phone = _vendorPhone;
    if (phone == null) return;
    final digits = phone.replaceAll(RegExp(r'[^0-9+]'), '');
    final uri = Uri.parse('https://wa.me/$digits');
    try {
      final launched = await launchUrl(uri, mode: LaunchMode.externalApplication);
      if (!launched && mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text("Couldn't open WhatsApp.")),
        );
      }
    } catch (_) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text("Couldn't open WhatsApp.")),
        );
      }
    }
  }

  String _timeLabel(DateTime dt) {
    final hour12 = dt.hour % 12 == 0 ? 12 : dt.hour % 12;
    final minute = dt.minute.toString().padLeft(2, '0');
    final period = dt.hour >= 12 ? 'PM' : 'AM';
    return '$hour12:$minute $period';
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: _bg,
      appBar: AppBar(
        backgroundColor: Colors.white,
        elevation: 0.5,
        iconTheme: const IconThemeData(color: _navy),
        titleSpacing: 0,
        title: Row(
          children: [
            Container(
              padding: const EdgeInsets.all(6),
              decoration: BoxDecoration(
                color: _mintBg,
                borderRadius: BorderRadius.circular(8),
              ),
              child: const Icon(Icons.smart_toy_outlined, color: _mint, size: 18),
            ),
            const SizedBox(width: 10),
            Expanded(
              child: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    widget.title,
                    style: const TextStyle(
                        color: _navy, fontSize: 15, fontWeight: FontWeight.bold),
                    overflow: TextOverflow.ellipsis,
                  ),
                  Text(
                    widget.subtitle,
                    style: const TextStyle(color: Colors.grey, fontSize: 11),
                    overflow: TextOverflow.ellipsis,
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
      body: Column(
        children: [
          Expanded(
            child: ListView.builder(
              controller: _scrollController,
              padding: const EdgeInsets.all(16),
              itemCount: _messages.length + (_isSending ? 1 : 0),
              itemBuilder: (context, index) {
                if (index >= _messages.length) {
                  return _buildTypingBubble();
                }
                return _buildMessageBubble(_messages[index]);
              },
            ),
          ),
          _buildQuickActionsBar(),
          if (_isShopContext && _vendorPhone != null) _buildWhatsAppButton(),
          _buildInputBar(),
        ],
      ),
    );
  }

  Widget _buildMessageBubble(ChatMessage msg) {
    final bool isUser = msg.role == 'user';

    final bubble = Container(
      constraints: BoxConstraints(maxWidth: MediaQuery.of(context).size.width * 0.68),
      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
      decoration: BoxDecoration(
        color: isUser ? _mint : Colors.white,
        borderRadius: BorderRadius.only(
          topLeft: const Radius.circular(14),
          topRight: const Radius.circular(14),
          bottomLeft: Radius.circular(isUser ? 14 : 2),
          bottomRight: Radius.circular(isUser ? 2 : 14),
        ),
        border: isUser ? null : Border.all(color: _border),
      ),
      child: Text(
        msg.text,
        style: TextStyle(
          color: isUser ? Colors.white : _navy,
          fontSize: 14,
          height: 1.4,
        ),
      ),
    );

    final timestamp = Padding(
      padding: EdgeInsets.only(top: 4, left: isUser ? 0 : 4, right: isUser ? 4 : 0),
      child: Text(
        _timeLabel(msg.timestamp),
        style: const TextStyle(fontSize: 10, color: Colors.grey),
      ),
    );

    final column = Column(
      crossAxisAlignment: isUser ? CrossAxisAlignment.end : CrossAxisAlignment.start,
      mainAxisSize: MainAxisSize.min,
      children: [bubble, timestamp],
    );

    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(
        mainAxisAlignment: isUser ? MainAxisAlignment.end : MainAxisAlignment.start,
        crossAxisAlignment: CrossAxisAlignment.end,
        children: isUser
            ? [Flexible(child: column)]
            : [_buildBotAvatar(), const SizedBox(width: 8), Flexible(child: column)],
      ),
    );
  }

  Widget _buildBotAvatar() {
    return Container(
      width: 28,
      height: 28,
      decoration: const BoxDecoration(color: _mintBg, shape: BoxShape.circle),
      child: const Icon(Icons.smart_toy_outlined, color: _mint, size: 16),
    );
  }

  Widget _buildTypingBubble() {
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.end,
        children: [
          _buildBotAvatar(),
          const SizedBox(width: 8),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
            decoration: BoxDecoration(
              color: Colors.white,
              borderRadius: BorderRadius.circular(14),
              border: Border.all(color: _border),
            ),
            child: const SizedBox(
              width: 14,
              height: 14,
              child: CircularProgressIndicator(strokeWidth: 2, color: _mint),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildQuickActionsBar() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.fromLTRB(16, 4, 16, 8),
      decoration: const BoxDecoration(
        color: Colors.white,
        border: Border(top: BorderSide(color: _border)),
      ),
      child: Wrap(
        spacing: 8,
        runSpacing: 8,
        children: _quickActions.map((a) {
          return InkWell(
            borderRadius: BorderRadius.circular(20),
            onTap: _isSending ? null : () => _sendMessage(a.label),
            child: Container(
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
              decoration: BoxDecoration(
                color: _bg,
                borderRadius: BorderRadius.circular(20),
                border: Border.all(color: _border),
              ),
              child: Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Icon(a.icon, size: 14, color: _navy),
                  const SizedBox(width: 6),
                  Text(a.label, style: const TextStyle(fontSize: 12.5, color: _navy)),
                ],
              ),
            ),
          );
        }).toList(),
      ),
    );
  }

  Widget _buildWhatsAppButton() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.fromLTRB(16, 0, 16, 8),
      color: Colors.white,
      child: OutlinedButton.icon(
        onPressed: _openWhatsApp,
        icon: const Icon(Icons.chat, size: 18, color: _whatsapp),
        label: const Text(
          "WhatsApp Message",
          style: TextStyle(color: _whatsapp, fontWeight: FontWeight.w600),
        ),
        style: OutlinedButton.styleFrom(
          side: const BorderSide(color: _whatsapp),
          padding: const EdgeInsets.symmetric(vertical: 12),
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(24)),
        ),
      ),
    );
  }

  Widget _buildInputBar() {
    return Container(
      padding: EdgeInsets.only(
        left: 12,
        right: 12,
        top: 10,
        bottom: MediaQuery.of(context).viewInsets.bottom + 10,
      ),
      decoration: BoxDecoration(
        color: Colors.white,
        boxShadow: [
          BoxShadow(color: Colors.black.withValues(alpha: 0.05), blurRadius: 10, offset: const Offset(0, -3)),
        ],
      ),
      child: Row(
        children: [
          Expanded(
            child: TextField(
              controller: _inputController,
              enabled: !_isSending,
              minLines: 1,
              maxLines: 4,
              textInputAction: TextInputAction.send,
              onSubmitted: (_) => _sendMessage(),
              style: const TextStyle(fontSize: 14),
              decoration: InputDecoration(
                hintText: _isShopContext
                    ? "Ask about products, price, or place an order..."
                    : "Type your message...",
                hintStyle: const TextStyle(fontSize: 13, color: Colors.grey),
                filled: true,
                fillColor: _bg,
                contentPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
                border: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(24),
                  borderSide: const BorderSide(color: _border),
                ),
                enabledBorder: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(24),
                  borderSide: const BorderSide(color: _border),
                ),
                focusedBorder: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(24),
                  borderSide: const BorderSide(color: _mint, width: 1.5),
                ),
              ),
            ),
          ),
          const SizedBox(width: 8),
          Container(
            decoration: const BoxDecoration(color: _mint, shape: BoxShape.circle),
            child: IconButton(
              onPressed: _isSending ? null : () => _sendMessage(),
              icon: const Icon(Icons.send, color: Colors.white, size: 20),
            ),
          ),
        ],
      ),
    );
  }
}

class _QuickAction {
  final String label;
  final IconData icon;
  const _QuickAction(this.label, this.icon);
}